import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {ALL_VIEWS,VIEW_ROLE_PERMISSIONS,isValidView,isViewPermittedForRole} from '../utils/navigation';
const read=(path:string)=>readFileSync(new URL(path,import.meta.url),'utf-8');
const app=read('../App.tsx'),layout=read('../components/Layout.tsx');
const termAdmin=read('../views/DigitalEnrollmentAdmin.tsx');
const tracking=read('../components/EnrollmentInvitationTracking.tsx');
const trackingPage=read('../views/EnrollmentTrackingPage.tsx');
assert.ok(ALL_VIEWS.includes('enrollment_tracking'));
assert.ok(isValidView('enrollment_tracking'));
assert.deepEqual(VIEW_ROLE_PERMISSIONS.enrollment_tracking,['super_admin','admin']);
assert.equal(isViewPermittedForRole('enrollment_tracking','teacher'),false);
assert.match(app,/case "enrollment_tracking"/);
assert.match(app,/featurePermissions\.enrollment_tracking\.view \? <EnrollmentTrackingPage/);
assert.match(layout,/id: "enrollment_tracking", label: "Acompanhamento de Termos"/);
assert.match(layout,/item\.id !== 'enrollment_tracking'/);
assert.doesNotMatch(termAdmin,/<EnrollmentInvitationTracking/);
assert.match(trackingPage,/<EnrollmentInvitationTracking/);
assert.match(tracking,/PAGE_SIZE=8/);
assert.match(tracking,/pageRows\.map\(r=><details/);
assert.match(tracking,/aria-label="Páginas dos termos"/);
assert.match(tracking,/setPage\(1\)/);
console.log('PASS: separate navigation, restricted access, compact rows and pagination');
